def _excel_column_name(index: int) -> str:
    """Return the one-based Excel column name used in a source formula."""
    name = ''
    while index:
        index, remainder = divmod(index - 1, 26)
        name = chr(ord('A') + remainder) + name
    return name


def _rewrite_embedded_chart_workbook(docx_path: Path, categories, series) -> None:
    """Replace stale template values in the chart's embedded workbook.

    Word persists direct SeriesCollection assignments in the chart cache but
    does not update the embedded XLSX.  Editing that XLSX after Word closes is
    deterministic and avoids launching an interactive Excel child process.
    """
    # lxml retains declarations referenced only by mc:Ignorable. ElementTree
    # drops them and can make an otherwise valid native XLSX unopenable.
    from lxml import etree as ET
    import posixpath

    spreadsheet = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'
    ns = {'x': spreadsheet}

    def cell(reference: str, value):
        node = ET.Element(f'{{{spreadsheet}}}c', {'r': reference})
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            ET.SubElement(node, f'{{{spreadsheet}}}v').text = str(value)
        else:
            node.set('t', 'inlineStr')
            inline = ET.SubElement(node, f'{{{spreadsheet}}}is')
            text = ET.SubElement(inline, f'{{{spreadsheet}}}t')
            text.text = str(value)
            if str(value) != str(value).strip():
                text.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
        return node

    with zipfile.ZipFile(docx_path, 'r') as document:
        document_infos = document.infolist()
        document_payloads = {
            info.filename: document.read(info.filename) for info in document_infos
        }
    workbook_parts = sorted(
        name for name in document_payloads
        if name.startswith('word/embeddings/') and name.lower().endswith('.xlsx')
    )
    if len(workbook_parts) != 1:
        raise RuntimeError(
            f'Expected one embedded chart workbook, found {len(workbook_parts)}'
        )
    workbook_part = workbook_parts[0]
    with zipfile.ZipFile(io.BytesIO(document_payloads[workbook_part]), 'r') as workbook:
        workbook_infos = workbook.infolist()
        workbook_payloads = {
            info.filename: workbook.read(info.filename) for info in workbook_infos
        }
    sheet_names = sorted(
        name for name in workbook_payloads
        if name.startswith('xl/worksheets/sheet') and name.endswith('.xml')
    )
    if not sheet_names:
        raise RuntimeError('Embedded chart workbook has no worksheet')
    sheet_name = sheet_names[0]
    sheet = ET.fromstring(workbook_payloads[sheet_name])
    sheet_data = sheet.find('x:sheetData', ns)
    if sheet_data is None:
        raise RuntimeError('Embedded chart worksheet has no sheetData')
    sheet_data.clear()

    header = ET.SubElement(sheet_data, f'{{{spreadsheet}}}row', {'r': '1'})
    # Excel table column names must be nonempty; a space is the native chart
    # template's visually blank category header.
    header.append(cell('A1', ' '))
    for column, item in enumerate(series, start=2):
        header.append(cell(f'{_excel_column_name(column)}1', item['name']))
    for row_index, category in enumerate(categories, start=2):
        row = ET.SubElement(
            sheet_data, f'{{{spreadsheet}}}row', {'r': str(row_index)}
        )
        row.append(cell(f'A{row_index}', category))
        for column, item in enumerate(series, start=2):
            row.append(cell(
                f'{_excel_column_name(column)}{row_index}',
                item['values'][row_index - 2],
            ))
    data_range = f'A1:{_excel_column_name(len(series) + 1)}{len(categories) + 1}'
    dimension = sheet.find('x:dimension', ns)
    if dimension is not None:
        dimension.set('ref', data_range)

    table_parts = sheet.find('x:tableParts', ns)
    if table_parts is not None:
        references = table_parts.findall('x:tablePart', ns)
        if len(references) != 1 or int(table_parts.get('count', '1')) != 1:
            raise RuntimeError('Expected one chart worksheet table')
        office_rel = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
        package_rel = 'http://schemas.openxmlformats.org/package/2006/relationships'
        rel_name = posixpath.join(posixpath.dirname(sheet_name), '_rels',
                                 posixpath.basename(sheet_name) + '.rels')
        if rel_name not in workbook_payloads:
            raise RuntimeError('Chart worksheet table relationships are missing')
        rels = ET.fromstring(workbook_payloads[rel_name])
        rel_id = references[0].get(f'{{{office_rel}}}id')
        matches = [rel for rel in rels.findall(f'{{{package_rel}}}Relationship')
                   if rel.get('Id') == rel_id]
        if (len(matches) != 1 or matches[0].get('TargetMode') == 'External'
                or not matches[0].get('Type', '').endswith('/table')):
            raise RuntimeError('Chart worksheet table relationship is invalid')
        target = matches[0].get('Target', '')
        table_name = (target.lstrip('/') if target.startswith('/') else
                      posixpath.normpath(posixpath.join(posixpath.dirname(sheet_name), target)))
        if table_name not in workbook_payloads:
            raise RuntimeError('Referenced chart worksheet table is missing')
        table = ET.fromstring(workbook_payloads[table_name])
        table.set('ref', data_range)
        auto_filter = table.find('x:autoFilter', ns)
        if auto_filter is not None:
            auto_filter.set('ref', data_range)
        columns = table.find('x:tableColumns', ns)
        if columns is None:
            raise RuntimeError('Chart worksheet table has no column definitions')
        columns.clear()
        names = [' ', *(item['name'] for item in series)]
        columns.set('count', str(len(names)))
        for index, name in enumerate(names, start=1):
            ET.SubElement(columns, f'{{{spreadsheet}}}tableColumn',
                          {'id': str(index), 'name': name})
        workbook_payloads[table_name] = ET.tostring(
            table, encoding='utf-8', xml_declaration=True
        )
    workbook_payloads[sheet_name] = ET.tostring(
        sheet, encoding='utf-8', xml_declaration=True
    )

    workbook_buffer = io.BytesIO()
    with zipfile.ZipFile(workbook_buffer, 'w') as workbook:
        for info in workbook_infos:
            workbook.writestr(info, workbook_payloads[info.filename])
    document_payloads[workbook_part] = workbook_buffer.getvalue()

    temp_path = docx_path.with_suffix('.workbook-rewrite.docx')
    try:
        with zipfile.ZipFile(temp_path, 'w') as document:
            for info in document_infos:
                document.writestr(info, document_payloads[info.filename])
        os.replace(temp_path, docx_path)
    finally:
        if temp_path.exists():
            temp_path.unlink()


