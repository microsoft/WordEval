    def generate_all(self, command: str = None, limit: int = None) -> Dict:
        """Generate all test cases for this test set."""
        configs = get_test_configs()
        fn_en_configs = get_footnote_endnote_configs()
        sort_configs = get_table_sort_configs()
        caption_configs = get_caption_insert_configs()
        chart_configs = get_chart_insert_configs()
        smartart_configs = get_smartart_insert_configs()
        icon_configs = get_icon_insert_configs()

        # Filter by command if specified
        if command:
            configs = [c for c in configs if c.idMso == command]
            fn_en_configs = [c for c in fn_en_configs if c.idMso == command]
            sort_configs = [c for c in sort_configs if c.idMso == command]
            caption_configs = [c for c in caption_configs if c.idMso == command]
            chart_configs = [c for c in chart_configs if c.idMso == command]
            smartart_configs = [c for c in smartart_configs if c.idMso == command]
            icon_configs = [c for c in icon_configs if c.idMso == command]

        if limit:
            total = (configs + fn_en_configs + sort_configs
                     + caption_configs + chart_configs + smartart_configs
                     + icon_configs)
            total = total[:limit]
            configs = [c for c in total if isinstance(c, HyperlinkInsertConfig)]
            fn_en_configs = [c for c in total if isinstance(c, FootnoteEndnoteConfig)]
            sort_configs = [c for c in total if isinstance(c, TableSortConfig)]
            caption_configs = [c for c in total if isinstance(c, CaptionInsertConfig)]
            chart_configs = [c for c in total if isinstance(c, ChartInsertConfig)]
            smartart_configs = [c for c in total if isinstance(c, SmartArtInsertConfig)]
            icon_configs = [c for c in total if isinstance(c, IconInsertConfig)]

        all_configs_list = (configs + fn_en_configs + sort_configs
                           + caption_configs + chart_configs + smartart_configs
                           + icon_configs)
        total_count = len(all_configs_list)
        all_idMsos = set(c.idMso for c in all_configs_list)

        print(f"\n=== Generating test cases for {total_count} configurations ===")
        print(f"Test set: {TEST_SET_NAME}")
        print(f"Output: {self.output_dir}\n")

        # Step 1: Generate input documents
        print("Step 1: Generating input documents...")
        self.generate_input_doc()
        if fn_en_configs:
            self.generate_footnote_endnote_inputs()
        if sort_configs or caption_configs:
            self._generate_table_input()
        if chart_configs or smartart_configs or icon_configs:
            self._generate_empty_input()
        print()

        summary = {
            'test_set': TEST_SET_NAME,
            'generated_at': datetime.now().isoformat(),
            'total_commands': len(all_idMsos),
            'total_test_cases': 0,
            'successful': 0,
            'failed': 0,
            'skipped': 0,
            'results': [],
        }

        def _process_config(config, gen_fn):
            print(f"\n{config.idMso}/{config.variation}...")
            result = gen_fn(config)
            summary['total_test_cases'] += 1
            if result.get('skipped'):
                summary['skipped'] += 1
            elif result['success']:
                summary['successful'] += 1
            else:
                summary['failed'] += 1
            summary['results'].append(result)
            status = 'SKIP' if result.get('skipped') else ('OK' if result['success'] else 'FAIL')
            print(f"  {status} - {result['message']}")

        # Step 2: Generate gold documents
        print("Step 2: Generating test cases...")
        for config in configs:
            _process_config(config, self.generate_gold)

        for config in fn_en_configs:
            _process_config(config, self.generate_footnote_endnote_gold)

        for config in sort_configs:
            _process_config(config, self.generate_table_sort_gold)

        for config in caption_configs:
            _process_config(config, self.generate_caption_insert_gold)

        for config in chart_configs:
            _process_config(config, self.generate_chart_insert_gold)

        for config in smartart_configs:
            _process_config(config, self.generate_smartart_insert_gold)

        for config in icon_configs:
            _process_config(config, self.generate_icon_insert_gold)

        # Save summary
        summary_path = self.output_dir / 'generation_summary.json'
        with open(summary_path, 'w', encoding='utf-8') as f:
            json.dump(summary, f, indent=2, ensure_ascii=False, sort_keys=True)

        self._print_summary(summary, summary_path)
        return summary

    def _print_summary(self, summary: Dict, summary_path: Path):
        """Print generation summary."""
        print(f"\n=== Generation Complete ===")
        print(f"\nResults\n")
        print("| Status     | Count |")
        print("|-----------|-------|")
        print(f"| Successful| {summary['successful']:<5} |")
        print(f"| Skipped   | {summary.get('skipped', 0):<5} |")
        print(f"| Failed    | {summary['failed']:<5} |")
        print(f"\nTotal test cases: {summary['total_test_cases']}")
        print(f"Summary saved to: {summary_path}")


