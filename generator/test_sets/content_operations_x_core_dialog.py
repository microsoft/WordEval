class ContentOperationsCoreDialogGenerator:
    """
    Generator for content_operations × core_dialog test cases.

    Handles:
    - HyperlinkInsert: 5 test cases (web link, mailto, grounding links, image hyperlinks)
    - FootnoteEndnoteDialog: 7 test cases (number format, numbering rule, custom symbol, standard insert)
    - SortDialogClassic: 2 test cases (sort by column ascending/descending)
    - CaptionInsert: 2 test cases (figure caption below, table caption above)
    - ChartInsert: 3 test cases (column, line, pie charts with explicit data)
    - SmartArtInsert: 2 test cases (basic list, hierarchy)
    - IconInsertFromFile: 2 test cases (blue star, orange circle icons)

    All use COM API directly — no ExecuteMso.
    """

    def __init__(self, output_dir: Path = None):
        self.output_dir = output_dir or (BENCHMARK_OUTPUT_DIR / TEST_SET_NAME)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.inputs_dir = self.output_dir / 'inputs'
        self.inputs_dir.mkdir(parents=True, exist_ok=True)
        self.input_path = None
        self.image_input_path = None
        self.table_input_path = None
        self.fn_en_input_paths: Dict[FootnoteEndnoteInputState, Path] = {}
        self.empty_input_path = None

    def generate_input_doc(self) -> Path:
        """Generate shared input documents."""
        # Generate doc_in_text.docx
        self._generate_text_input()
        # Generate doc_in_with_image.docx
        self._generate_image_input()
        return self.input_path

    def _generate_text_input(self) -> Path:
        """Generate doc_in_text.docx with simple text."""
