    def generate_chart_insert_gold(self, config: ChartInsertConfig) -> Dict:
        """Generate gold.docx for a ChartInsert test case."""
        test_dir = self.output_dir / config.idMso / config.variation
        test_dir.mkdir(parents=True, exist_ok=True)

        gold_path = test_dir / 'gold.docx'
        spec_path = test_dir / 'spec.json'
        input_path = self.empty_input_path

        result = {
            'idMso': config.idMso,
            'variation': config.variation,
            'success': False,
            'message': '',
            'paths': {
                'doc_in': str(input_path),
                'gold': str(gold_path),
                'spec': str(spec_path),
            }
        }

        if config.skip_reason:
            result['message'] = f'Skipped: {config.skip_reason}'
            result['skipped'] = True
            spec = self._generate_chart_insert_spec(config)
            spec['skipped'] = True
            spec['skip_reason'] = config.skip_reason
            write_spec_if_changed(spec_path, spec)
            return result

        wd = ensure_word()
        try:
            doc = wd.Documents.Open(str(input_path.absolute()))

            # Position at start (empty doc)
            wd.Selection.HomeKey(Unit=6)  # wdStory
            time.sleep(0.1)

            # Insert chart
            doc.InlineShapes.AddChart2(-1, config.chart_type)
            time.sleep(3)
            chart = doc.InlineShapes(1).Chart

            # Set the visible chart cache through Word's object model.
            while chart.SeriesCollection().Count > len(config.series):
                chart.SeriesCollection(chart.SeriesCollection().Count).Delete()
                time.sleep(0.2)
            for i, s in enumerate(config.series, 1):
                if i <= chart.SeriesCollection().Count:
                    sc = chart.SeriesCollection(i)
                else:
                    sc = chart.SeriesCollection().NewSeries()
                sc.Name = s['name']
                sc.Values = s['values']
                sc.XValues = config.categories
                time.sleep(0.2)

            time.sleep(0.5)
            doc.SaveAs(str(gold_path.absolute()), FileFormat=16)
            doc.Close(False)
            time.sleep(0.2)
            _rewrite_embedded_chart_workbook(
                gold_path, config.categories, config.series
            )

            spec = self._generate_chart_insert_spec(config)
            write_spec_if_changed(spec_path, spec)

            result['success'] = True
            result['message'] = 'Test case generated successfully'

        except Exception as e:
            result['message'] = f'Error: {str(e)}'
            import traceback
            traceback.print_exc()

        return result

