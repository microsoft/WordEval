    def generate_gold(self, config: HyperlinkInsertConfig) -> Dict:
        """Generate gold.docx by inserting hyperlink via COM."""
        test_dir = self.output_dir / config.idMso / config.variation
        test_dir.mkdir(parents=True, exist_ok=True)

        gold_path = test_dir / 'gold.docx'
        spec_path = test_dir / 'spec.json'

        # Determine which input doc to use
        input_doc_path = self.image_input_path if config.anchor_mode == 'image' else self.input_path

        result = {
            'idMso': config.idMso,
            'variation': config.variation,
            'success': False,
            'message': '',
            'paths': {
                'doc_in': str(input_doc_path),
                'gold': str(gold_path),
                'spec': str(spec_path),
            }
        }

        # Check for skip
        if config.skip_reason:
            result['message'] = f'Skipped: {config.skip_reason}'
            result['skipped'] = True
            spec = self._generate_spec(config)
            spec['skipped'] = True
            spec['skip_reason'] = config.skip_reason
            write_spec_if_changed(spec_path, spec)
            return result

        wd = ensure_word()
        try:
            doc = wd.Documents.Open(str(input_doc_path.absolute()))

            if config.anchor_mode == 'image':
                # Add hyperlink to the first inline shape (image)
                if doc.InlineShapes.Count == 0:
                    result['message'] = 'No inline shapes found in input document'
                    doc.Close(False)
                    return result

                anchor_range = doc.InlineShapes(1).Range

                # Add hyperlink to shape (no TextToDisplay for shape hyperlinks)
                doc.Hyperlinks.Add(
                    Anchor=anchor_range,
                    Address=config.address,
                )
            else:
                # Find anchor text
                wd.Selection.HomeKey(Unit=6)  # wdStory
                wd.Selection.Find.ClearFormatting()
                found = wd.Selection.Find.Execute(
                    FindText=config.anchor_text,
                    MatchCase=False,
                    MatchWholeWord=True,
                    Forward=True
                )

                if not found:
                    result['message'] = f"Failed to find anchor text: {config.anchor_text}"
                    doc.Close(False)
                    return result

                if config.anchor_mode == 'replace':
                    # Use selected text range as anchor (replaces "TARGET" with display text)
                    anchor_range = wd.Selection.Range
                else:
                    # Position after anchor text, insert a space first
                    wd.Selection.Collapse(Direction=0)  # wdCollapseEnd
                    wd.Selection.TypeText(' ')
                    anchor_range = wd.Selection.Range

                # Add hyperlink
                doc.Hyperlinks.Add(
                    Anchor=anchor_range,
                    Address=config.address,
                    TextToDisplay=config.text_to_display
                )

            time.sleep(0.3)

            # Save as gold
            doc.SaveAs(str(gold_path.absolute()), FileFormat=16)
            doc.Close(False)
            time.sleep(0.2)

            # Generate spec
            spec = self._generate_spec(config)
            write_spec_if_changed(spec_path, spec)

            result['success'] = True
            result['message'] = 'Test case generated successfully'

        except Exception as e:
            result['message'] = f'Error: {str(e)}'
            import traceback
            traceback.print_exc()

        return result

