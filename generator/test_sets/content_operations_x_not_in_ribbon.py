"""
Test case generator for content_operations × not_in_ribbon.

Handles commands available only via context menu (not in ribbon):
- HyperlinkRemove: Delete hyperlinks while keeping display text
- HyperlinkEdit: Change hyperlink display text

All operations use doc.Hyperlinks API directly (no ExecuteMso).

Key Design:
- Configuration-driven approach (HyperlinkModifyConfig dataclass)
- Two shared input docs with existing hyperlinks:
  - doc_in_with_web_link.docx: text with Bing hyperlink
  - doc_in_with_mailto.docx: text with mailto hyperlink
- Gold documents generated by modifying/removing hyperlinks via COM
"""

import json
import time
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Dict, List, Optional

from ..config import (
    BENCHMARK_OUTPUT_DIR,
)
from ..execution.setup import ensure_word, finalize_word
from generator.test_sets.spec_utils import write_spec_if_changed


# =============================================================================
# CONFIGURATION
# =============================================================================

TEST_SET_NAME = 'content_operations_x_not_in_ribbon'


class InputState(Enum):
    """Input document state."""
    WITH_WEB_LINK = "with_web_link"
    WITH_MAILTO = "with_mailto"


# Input document specs
INPUT_DOCS = {
    InputState.WITH_WEB_LINK: {
        'filename': 'doc_in_with_web_link.docx',
        'text_before': 'Visit ',
        'link_text': 'Bing',
        'text_after': ' for more.',
        'address': 'https://www.bing.com',
    },
    InputState.WITH_MAILTO: {
        'filename': 'doc_in_with_mailto.docx',
        'text_before': 'Contact ',
        'link_text': 'jane.doe@example.com',
        'text_after': ' for details.',
        'address': 'mailto:jane.doe@example.com',
    },
}


@dataclass
class HyperlinkModifyConfig:
    """Configuration for a single hyperlink modify/delete test case."""
    idMso: str
    variation: str
    input_state: InputState
    operation: str                        # 'delete' | 'change_display_text'
    new_display_text: Optional[str] = None  # For change_display_text only
    description: str = ""
    skip_reason: Optional[str] = None


def get_test_configs() -> List[HyperlinkModifyConfig]:
    """Get all test case configurations for this test set."""
    return [
        # HyperlinkRemove test cases
        HyperlinkModifyConfig(
            idMso='HyperlinkRemove',
            variation='delete_web_link',
            input_state=InputState.WITH_WEB_LINK,
            operation='delete',
            description='Delete web hyperlink, keep display text',
        ),
        HyperlinkModifyConfig(
            idMso='HyperlinkRemove',
            variation='delete_mailto',
            input_state=InputState.WITH_MAILTO,
            operation='delete',
            description='Delete mailto hyperlink, keep display text',
        ),

        # HyperlinkEdit test cases
        HyperlinkModifyConfig(
            idMso='HyperlinkEdit',
            variation='change_display_text_web',
            input_state=InputState.WITH_WEB_LINK,
            operation='change_display_text',
            new_display_text='hello world',
            description='Change web hyperlink display text to "hello world"',
        ),
        HyperlinkModifyConfig(
            idMso='HyperlinkEdit',
            variation='change_display_text_mailto',
            input_state=InputState.WITH_MAILTO,
            operation='change_display_text',
            new_display_text='Jane',
            description='Change mailto hyperlink display text to "Jane"',
        ),
    ]


# =============================================================================
# GENERATOR CLASS
# =============================================================================

class ContentOperationsNotInRibbonGenerator:
    """
    Generator for content_operations × not_in_ribbon test cases.

    Handles:
    - HyperlinkRemove: 2 test cases (delete web link, delete mailto)
    - HyperlinkEdit: 2 test cases (change display text web, change display text mailto)

    All use doc.Hyperlinks API directly — no ExecuteMso.
    """

    def __init__(self, output_dir: Path = None):
        self.output_dir = output_dir or (BENCHMARK_OUTPUT_DIR / TEST_SET_NAME)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.inputs_dir = self.output_dir / 'inputs'
        self.inputs_dir.mkdir(parents=True, exist_ok=True)
        self.input_paths: Dict[InputState, Path] = {}

    def generate_input_docs(self) -> Dict[InputState, Path]:
        """Generate shared input documents."""
        for input_state, doc_spec in INPUT_DOCS.items():
            input_path = self.inputs_dir / doc_spec['filename']

            if input_path.exists():
                print(f"  Input already exists: {input_path}")
                self.input_paths[input_state] = input_path
                continue

            print(f"  Generating input: {input_path}")

            wd = ensure_word()
            try:
                doc = wd.Documents.Add()

                # Hyperlink input docs
                wd.Selection.TypeText(doc_spec['text_before'])
                link_start = wd.Selection.Range.Start
                wd.Selection.TypeText(doc_spec['link_text'])
                link_end = wd.Selection.Range.End
                wd.Selection.TypeText(doc_spec['text_after'])
                anchor_range = doc.Range(link_start, link_end)
                doc.Hyperlinks.Add(
                    Anchor=anchor_range,
                    Address=doc_spec['address'],
                    TextToDisplay=doc_spec['link_text']
                )

                time.sleep(0.3)

                doc.SaveAs(str(input_path.absolute()), FileFormat=16)
                doc.Close(False)
                time.sleep(0.2)

                self.input_paths[input_state] = input_path
                print(f"    Created: {input_path}")

            except Exception as e:
                print(f"    Error creating input: {e}")
                raise

        return self.input_paths

    def generate_gold(self, config: HyperlinkModifyConfig) -> Dict:
        """Generate gold.docx by modifying/deleting hyperlink via COM."""
        test_dir = self.output_dir / config.idMso / config.variation
        test_dir.mkdir(parents=True, exist_ok=True)

        gold_path = test_dir / 'gold.docx'
        spec_path = test_dir / 'spec.json'

        input_path = self.input_paths[config.input_state]

        result = {
            'idMso': config.idMso,
            'variation': config.variation,
            'success': False,
            'message': '',
            'paths': {
                'doc_in': str(input_path),
                'gold': str(gold_path),
                'spec': str(spec_path),
            }
        }

        # Check for skip
        if config.skip_reason:
            result['message'] = f'Skipped: {config.skip_reason}'
            result['skipped'] = True
            spec = self._generate_spec(config)
            spec['skipped'] = True
            spec['skip_reason'] = config.skip_reason
            write_spec_if_changed(spec_path, spec)
            return result

        wd = ensure_word()
        try:
            doc = wd.Documents.Open(str(input_path.absolute()))
            time.sleep(0.5)

            if config.operation == 'delete':
                # Delete all hyperlinks (keeps display text)
                while doc.Hyperlinks.Count > 0:
                    doc.Hyperlinks(1).Delete()
                    time.sleep(0.1)

            elif config.operation == 'change_display_text':
                # Change display text of first hyperlink
                if doc.Hyperlinks.Count > 0:
                    doc.Hyperlinks(1).TextToDisplay = config.new_display_text
                else:
                    result['message'] = 'No hyperlinks found in input document'
                    doc.Close(False)
                    return result

            time.sleep(0.3)

            # Save as gold
            doc.SaveAs(str(gold_path.absolute()), FileFormat=16)
            doc.Close(False)
            time.sleep(0.2)

            # Generate spec
            spec = self._generate_spec(config)
            write_spec_if_changed(spec_path, spec)

            result['success'] = True
            result['message'] = 'Test case generated successfully'

        except Exception as e:
            result['message'] = f'Error: {str(e)}'
            import traceback
            traceback.print_exc()

        return result

    def _generate_spec(self, config: HyperlinkModifyConfig) -> Dict:
        """Generate spec.json for a test case."""
        doc_spec = INPUT_DOCS[config.input_state]
        input_filename = doc_spec['filename']

        # Determine verification based on operation
        if config.operation == 'delete':
            primary_verification = {
                'method': 'hyperlink_verification',
                'description': 'Verify all hyperlinks removed, display text preserved',
            }
        else:  # change_display_text
            primary_verification = {
                'method': 'hyperlink_verification',
                'description': 'Compare hyperlink display text changed',
            }

        spec = {
            'idMso': config.idMso,
            'behavior': 'content_operations',
            'scope': 'not_in_ribbon',
            'variation': config.variation,
            'generated_at': datetime.now().isoformat(),

            'precondition': {
                'input_state': config.input_state.value,
            },

            'execution': {
                'operation': config.operation,
            },

            'verification': {
                'primary': primary_verification,
            },

            'files': {
                'doc_in': f'../../inputs/{input_filename}',
                'gold': 'gold.docx',
            }
        }

        if config.new_display_text:
            spec['execution']['new_display_text'] = config.new_display_text

        return spec

    def generate_all(self, command: str = None, limit: int = None) -> Dict:
        """Generate all test cases for this test set."""
        configs = get_test_configs()

        # Filter by command if specified
        if command:
            configs = [c for c in configs if c.idMso == command]

        if limit:
            configs = configs[:limit]

        print(f"\n=== Generating test cases for {len(configs)} configurations ===")
        print(f"Test set: {TEST_SET_NAME}")
        print(f"Output: {self.output_dir}\n")

        # Step 1: Generate input documents
        print("Step 1: Generating input documents...")
        self.generate_input_docs()
        print()

        summary = {
            'test_set': TEST_SET_NAME,
            'generated_at': datetime.now().isoformat(),
            'total_commands': len(set(c.idMso for c in configs)),
            'total_test_cases': 0,
            'successful': 0,
            'failed': 0,
            'skipped': 0,
            'results': [],
        }

        # Step 2: Generate gold documents
        print("Step 2: Generating test cases...")
        for config in configs:
            print(f"\n{config.idMso}/{config.variation}...")

            result = self.generate_gold(config)

            summary['total_test_cases'] += 1
            if result.get('skipped'):
                summary['skipped'] += 1
            elif result['success']:
                summary['successful'] += 1
            else:
                summary['failed'] += 1
            summary['results'].append(result)

            status = 'SKIP' if result.get('skipped') else ('OK' if result['success'] else 'FAIL')
            print(f"  {status} - {result['message']}")

        # Save summary
        summary_path = self.output_dir / 'generation_summary.json'
        with open(summary_path, 'w', encoding='utf-8') as f:
            json.dump(summary, f, indent=2, ensure_ascii=False, sort_keys=True)

        self._print_summary(summary, summary_path)
        return summary

    def _print_summary(self, summary: Dict, summary_path: Path):
        """Print generation summary."""
        print(f"\n=== Generation Complete ===")
        print(f"\nResults\n")
        print("| Status     | Count |")
        print("|-----------|-------|")
        print(f"| Successful| {summary['successful']:<5} |")
        print(f"| Skipped   | {summary.get('skipped', 0):<5} |")
        print(f"| Failed    | {summary['failed']:<5} |")
        print(f"\nTotal test cases: {summary['total_test_cases']}")
        print(f"Summary saved to: {summary_path}")


# =============================================================================
# CLI
# =============================================================================

def main():
    """CLI entry point."""
    import argparse

    parser = argparse.ArgumentParser(
        description=f'Generate test cases for {TEST_SET_NAME}'
    )
    parser.add_argument('--command', '-c', help='Generate for a specific command')
    parser.add_argument('--limit', '-l', type=int, help='Limit number of test cases')
    parser.add_argument('--output', '-o', help='Output directory')

    # Accept but ignore these args passed by run.py
    parser.add_argument('--timeout-gen', type=float, help='Timeout (ignored)')
    parser.add_argument('--hidden', action='store_true', help='Hidden mode (ignored)')

    args = parser.parse_args()

    output_dir = Path(args.output) if args.output else None
    generator = ContentOperationsNotInRibbonGenerator(output_dir=output_dir)
    generator.generate_all(command=args.command, limit=args.limit)


if __name__ == '__main__':
    main()
