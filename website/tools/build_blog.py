"""Build the Chinese article from the English page and keyed translations."""
from pathlib import Path
import json
from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parents[1]


def build():
    page = BeautifulSoup((ROOT / 'blog/index.html').read_text(encoding='utf-8'), 'html.parser')
    translations = json.loads((ROOT / 'blog/zh-CN.json').read_text(encoding='utf-8'))
    nodes = page.select('[data-i18n]')
    keys = [node['data-i18n'] for node in nodes]
    if len(set(keys)) != len(keys) or set(keys) != set(translations):
        raise ValueError(f'Translation keys differ: {set(keys) ^ set(translations)}')
    for node in nodes:
        node.clear()
        node.extend(BeautifulSoup(translations[node['data-i18n']], 'html.parser').contents)
    page.html['lang'] = 'zh-CN'
    page.find('meta', attrs={'name': 'description'})['content'] = 'WordEval 用 Word 原生文档属性检验编辑结果，通过原子任务与组合任务评测智能体的编辑准确性。'
    labels = {'Introduction': '引言', 'Verification': '验证', 'Construction': '构建', 'Tasks': '任务', 'Results': '结果', 'Conclusion': '结语'}
    for anchor in page.select('.site-section-nav a'):
        anchor.string = labels[anchor.get_text()]
    page.select_one('.site-section-nav')['aria-label'] = '文章目录'
    page.select_one('.directory-toggle').string = '目录 ☰'
    page.select_one('.article-location')['aria-label'] = '当前位置'
    page.select_one('.article-location a')['aria-label'] = 'WordEval 项目主页'
    for anchor in page.select('.languages a'):
        anchor.attrs.pop('aria-current', None)
        if anchor['hreflang'] == 'zh-CN':
            anchor['aria-current'] = 'page'
    (ROOT / 'blog/zh.html').write_text('<!-- Generated by tools/build_blog.py. -->\n' + str(page).rstrip() + '\n', encoding='utf-8')
    print(f'Built Chinese article: {len(keys)} translated blocks.')


if __name__ == '__main__':
    build()
